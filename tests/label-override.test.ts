describe('行ラベルの上書き', () => {
  it.each(CASES)('%s → %s', (name, l1, l2) => {
    expect(labelOverride(name)).toEqual({ l1, l2 });
  });

  it('具体的な規則が先: 「究極でスコア報酬5倍」は「スコア報酬5倍」にならない', () => {
    expect(labelOverride('「守護獣の森」の究極難易度でスコア報酬に「5倍」のスペシャルボーナス!')?.l1).toBe('究極でスコア報酬5倍');
  });

  it('指定により変形しない: スワイプトレジャー・DREAMDAZE Ⅳ・ガチャ系は上書きなし', () => {
    expect(labelOverride('スワイプして大量のゲーム内アイテムを獲得できる「スワイプトレジャー」が5/9より期間限定で開催！ #1')).toBeNull();
    expect(labelOverride('DREAMDAZE Ⅳ開催記念クエスト「あゆむ」が7/11より期間限定で出現！ #1')).toBeNull();
    for (const n of ['ガチャ「モンストジェネレーション 2013＆2014」', 'ガチャ「ブレイブ・ガールズ2 〜果敢なる女傑たち〜」', '「フレンドと2人で引ける♪チョイスガチャ」']) expect(labelOverride(n)).toBeNull();
  });

  it('全ての上書きが、1行に収まる幅(全角15.5文字相当)以内。2行目も同様', () => {
    for (const r of cfg.rules) {
      expect(labelWidth(r.label), r.label).toBeLessThanOrEqual(MAX_LABEL_WIDTH);
      if ('desc' in r) expect(labelWidth(r.desc as string), r.label).toBeLessThanOrEqual(MAX_LABEL_WIDTH);
    }
  });

  it('labelWidth: 全角1・半角英数0.6・記号/空白0.35', () => {
    expect(labelWidth('あいう')).toBe(3);
    expect(labelWidth('CM')).toBeCloseTo(1.2);
    expect(labelWidth('a b!')).toBeCloseTo(0.6 + 0.35 + 0.6 + 0.35);
  });

  it('rowLabel: クエスト・キャンペーンは上書きし(折り返さない)、ガチャには適用しない', () => {
    const name = 'CM視聴ミッションでレアアイテム確率UP!';
    expect(rowLabel('quest', { name })).toEqual({ l1: 'CM視聴でレアアイテム確率UP', l2: null, wrap: false });
    expect(rowLabel('campaign', { name }).l1).toBe('CM視聴でレアアイテム確率UP');
    const g = rowLabel('gacha', { name: 'ガチャ「CM視聴ミッションでレアアイテム確率UP」開催!' });
    expect(g.l1).toBe('CM視聴ミッションでレアアイテム確率UP'); // ガチャは「」の中身のまま
  });
});

